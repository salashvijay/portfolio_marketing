(function () {
  "use strict";
  var $ = function (s) { return document.querySelector(s); };
  var esc = function (v) { return String(v == null ? "" : v).replace(/[&<>"']/g, function (c) { return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]; }); };

  var BLOCKS = {
    chat: {
      title: "Chat assistant",
      art: "Article 50(1): people must be told they are interacting with an AI system, unless it is obvious.",
      text: function (b, h) {
        return "First message (shown before the person types):\n" +
          "Hi! I'm " + b + "'s AI assistant. I'm an automated system, not a person, and I can make mistakes. " +
          "To talk to someone from our team at any time, " + h + ".\n\n" +
          "Label next to the chat window:\nAI assistant · answers may be inaccurate · " + h;
      },
      check: ["Show the notice before or at the first message, not only in your privacy policy.",
              "Keep a visible way to reach a person throughout the chat.",
              "Answer only from information you have approved. You are responsible for what it tells customers."]
    },
    voice: {
      title: "Voice agent",
      art: "Article 50(1): tell callers they are speaking to an AI. Other laws may also need consent to record (and, in the US, prior consent for AI-voiced outbound calls under the TCPA).",
      text: function (b, h) {
        return "Opening line:\n\"Hello, you've reached " + b + ". I'm an automated AI assistant. This call may be recorded to help us serve you. " +
          "You can ask for a person at any time, just say 'agent'.\"";
      },
      check: ["Say it in the first sentence of every call.",
              "Make 'agent' or 'person' actually transfer the call, or take a message for a callback.",
              "Check recording-consent rules in each country or state you call or receive calls from."]
    },
    email: {
      title: "AI-written replies",
      art: "Article 50(1) covers AI systems people interact with directly. A short note is good practice when replies are sent without a person reviewing them.",
      text: function (b, h) {
        return "Footer for replies sent without review:\nThis reply was written by " + b + "'s AI assistant. If anything looks wrong, reply 'human' and a member of our team will help.\n\n" +
          "For replies a person checked before sending, a note is not normally needed.";
      },
      check: ["Decide which messages are sent automatically and which a person reviews first.",
              "Keep a log of automatic replies in case a customer disputes one."]
    },
    media: {
      title: "Realistic AI images, audio or video",
      art: "Article 50(4): if you publish deepfakes (realistic content showing real-looking people, places or events), disclose that they are AI-generated or manipulated. Artistic or satirical work gets a lighter, non-intrusive notice.",
      text: function (b) {
        return "Label on or next to the content:\nAI-generated · This image/video was created or edited with AI by " + b + ".";
      },
      check: ["Put the label where people see it with the content, not only in a caption elsewhere.",
              "Keep the AI tool's own machine-readable marking (C2PA or watermark). Don't strip it when editing.",
              "Never use a real person's likeness without their permission."]
    },
    text: {
      title: "AI-written articles for the public",
      art: "Article 50(4): AI-generated text published to inform the public on matters of public interest must be disclosed, unless a person reviewed it and someone holds editorial responsibility.",
      text: function (b) {
        return "Byline note:\nThis article was drafted with AI and reviewed by " + b + "'s editorial team, who are responsible for its content.\n\n" +
          "If no person reviews it before publishing:\nThis article was generated by AI.";
      },
      check: ["Name who is editorially responsible, or label the text as AI-generated.",
              "Check facts and sources before publishing. Google also penalises mass-produced low-value pages."]
    },
    emotion: {
      title: "Emotion recognition or biometric categorisation",
      art: "Article 50(3): people exposed to these systems must be told, and personal data rules (GDPR) apply. Emotion recognition at work and in education is banned under Article 5, except for medical or safety reasons.",
      text: function (b, h) {
        return "Notice before use:\n" + b + " uses an AI system that analyses [facial expressions / voice tone] to [purpose]. " +
          "Your data is processed as described in our privacy notice. To ask questions or object, " + h + ".";
      },
      check: ["Check first that the use is allowed at all. It is banned in workplaces and schools, with narrow exceptions.",
              "You will usually need a GDPR data protection impact assessment.",
              "Get legal advice before launching."]
    }
  };

  $("#go").addEventListener("click", function () {
    var b = $("#biz").value.trim() || "our company";
    var h = $("#human").value.trim();
    h = h ? (h.indexOf("@") > 0 ? "email " + h : h) : "ask for a person";
    var picked = Array.prototype.filter.call(document.querySelectorAll(".use"), function (c) { return c.checked; }).map(function (c) { return c.value; });
    if (!picked.length) { $("#out").innerHTML = '<p class="verdict bad">Tick at least one place where you use AI.</p>'; return; }
    var out = picked.map(function (k, i) {
      var x = BLOCKS[k];
      return '<div class="panel"><h2 style="margin-top:0">' + esc(x.title) + '</h2><p class="fine">' + esc(x.art) + "</p>" +
        '<pre class="out" id="t' + i + '">' + esc(x.text(b, h)) + '</pre><p><button class="ghost" data-copy="t' + i + '">Copy text</button></p>' +
        "<b>Checklist</b><ul>" + x.check.map(function (c) { return "<li>" + esc(c) + "</li>"; }).join("") + "</ul></div>";
    }).join("");
    $("#out").innerHTML = out + '<div class="panel"><b>For every business using AI</b><ul>' +
      "<li>Keep a simple list of the AI tools you use, what each one does and who is responsible for it.</li>" +
      "<li>Article 4 asks you to support AI literacy: a short training for staff who use these tools, with a record of who attended.</li>" +
      "<li>Check each AI vendor's terms for data use and where data is stored.</li></ul></div>";
  });

  document.addEventListener("click", function (e) {
    var id = e.target.getAttribute && e.target.getAttribute("data-copy");
    if (!id) return;
    var t = document.getElementById(id).textContent;
    (navigator.clipboard ? navigator.clipboard.writeText(t) : Promise.reject()).then(function () { e.target.textContent = "Copied ✓"; },
      function () { e.target.textContent = "Select the text and copy it"; });
  });
})();
